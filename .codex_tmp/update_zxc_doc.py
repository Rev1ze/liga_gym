def set_cell_text(cell, text):
    cell.text = text
    for paragraph in cell.paragraphs:
        paragraph.alignment = WD_PARAGRAPH_ALIGNMENT.LEFT
        paragraph.paragraph_format.space_after = Pt(0)
        paragraph.paragraph_format.line_spacing = 1.0
        for run in paragraph.runs:
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
            run.font.size = Pt(10)


def set_cell_width(cell, width):
    cell.width = width
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_w = tc_pr.first_child_found_in("w:tcW")
    if tc_w is None:
        tc_w = OxmlElement("w:tcW")
        tc_pr.append(tc_w)
    tc_w.set(qn("w:w"), str(int(width.cm * 567)))
    tc_w.set(qn("w:type"), "dxa")


def main():
    doc = Document(DOCX_PATH)
    table = doc.tables[0]

    while len(table.rows) > 1:
        row = table.rows[-1]
        row._tr.getparent().remove(row._tr)

    header = table.rows[0]
    for idx, text in enumerate(("Сообщение", "Причина", "Действия пользователя")):
        set_cell_text(header.cells[idx], text)
        for paragraph in header.cells[idx].paragraphs:
            for run in paragraph.runs:
                run.bold = True

    for message, reason, action in ROWS:
        row = table.add_row()
        for cell, text in zip(row.cells, (message, reason, action)):
            set_cell_text(cell, text)

    widths = [Cm(5.2), Cm(5.7), Cm(5.7)]
    for row_idx, row in enumerate(table.rows):
        if row_idx == 0:
            tr_pr = row._tr.get_or_add_trPr()
            if tr_pr.find(qn("w:tblHeader")) is None:
                tbl_header = OxmlElement("w:tblHeader")
                tbl_header.set(qn("w:val"), "true")
                tr_pr.append(tbl_header)
        for idx, cell in enumerate(row.cells):
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            set_cell_width(cell, widths[idx])

    for paragraph in doc.paragraphs:
        if paragraph.text.strip().startswith("Таблица 2.14"):
            for run in paragraph.runs:
                run.font.name = "Times New Roman"
                run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
                run.font.size = Pt(12)

    doc.save(DOCX_PATH)
    print(f"saved {DOCX_PATH}")
    print(f"rows including header: {len(table.rows)}")


if __name__ == "__main__":
    main()
