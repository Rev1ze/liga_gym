IMG_DIR = Path(".codex_tmp/zxc_images")


def extract_images_in_order():
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    doc = Document(SRC)
    images = []
    counter = 0
    for para in doc.paragraphs:
        blips = para._p.xpath(".//a:blip")
        for blip in blips:
            rel_id = blip.get(qn("r:embed"))
            if not rel_id:
                continue
            counter += 1
            part = doc.part.related_parts[rel_id]
            ext = part.content_type.split("/")[-1].replace("jpeg", "jpg")
            path = IMG_DIR / f"image_{counter:02d}.{ext}"
            path.write_bytes(part.blob)
            images.append(path)
    return images


def add(doc, text=""):
    doc.add_paragraph(text)


def add_image(doc, images, index, caption):
    if index - 1 < len(images):
        p = doc.add_paragraph()
        run = p.add_run()
        run.add_picture(str(images[index - 1]), width=Inches(4.8))
    else:
        add(doc, f"!!!КАРТИНКА ВСТАВИТЬ ИЗ ИСХОДНОГО ДОКУМЕНТА, РИСУНОК {caption}!!!!")
    add(doc, caption)


def add_placeholder(doc, caption, place):
    add(doc, f"!!!КАРТИНКА ВСТАВИТЬ ИЗ {place}!!!!")
    add(doc, caption)


