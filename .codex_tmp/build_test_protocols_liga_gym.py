from pathlib import Path

from docx import Document


OUT = Path("docs/protokoly_testirovaniya_liga_gym.docx")


def add_text(doc, text):
    doc.add_paragraph(text)


def add_protocol_table(doc, caption, rows):
    doc.add_paragraph(caption)
    table = doc.add_table(rows=1, cols=2)
    table.style = "Table Grid"
    table.rows[0].cells[0].text = "Поле"
    table.rows[0].cells[1].text = "Описание"

    for field, description in rows:
        cells = table.add_row().cells
        cells[0].text = field
        cells[1].text = description

    doc.add_paragraph()


